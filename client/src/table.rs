//! USB HID keyboard page (0x07) usage ID → macOS CGKeyCode。
//!
//! 纯静态查表,无状态。CGKeyCode 即 HIToolbox/Events.h 里的 kVK_*
//! 虚拟键码(ANSI 布局)。注意 F13/F14/F15/F16 的编号顺序是 ADB 的
//! 历史遗留(F16=0x6A 在 F14=0x6B 之前),不是笔误。
//!
//! 未收录的 usage(媒体键、Menu 等)返回 None,由调用方忽略。

use core_graphics::event::CGKeyCode;

pub fn hid_to_mac(usage: u16) -> Option<CGKeyCode> {
    Some(match usage {
        // 字母区:HID 0x04..=0x1d 是 a..z
        0x04 => 0x00, // A
        0x05 => 0x0B, // B
        0x06 => 0x08, // C
        0x07 => 0x02, // D
        0x08 => 0x0E, // E
        0x09 => 0x03, // F
        0x0A => 0x05, // G
        0x0B => 0x04, // H
        0x0C => 0x22, // I
        0x0D => 0x26, // J
        0x0E => 0x28, // K
        0x0F => 0x25, // L
        0x10 => 0x2E, // M
        0x11 => 0x2D, // N
        0x12 => 0x1F, // O
        0x13 => 0x23, // P
        0x14 => 0x0C, // Q
        0x15 => 0x0F, // R
        0x16 => 0x01, // S
        0x17 => 0x11, // T
        0x18 => 0x20, // U
        0x19 => 0x09, // V
        0x1A => 0x0D, // W
        0x1B => 0x07, // X
        0x1C => 0x10, // Y
        0x1D => 0x06, // Z
        // 数字区
        0x1E => 0x12, // 1
        0x1F => 0x13, // 2
        0x20 => 0x14, // 3
        0x21 => 0x15, // 4
        0x22 => 0x17, // 5
        0x23 => 0x16, // 6
        0x24 => 0x1A, // 7
        0x25 => 0x1C, // 8
        0x26 => 0x19, // 9
        0x27 => 0x1D, // 0
        // 编辑与控制区
        0x28 => 0x24, // Enter → Return
        0x29 => 0x35, // Escape
        0x2A => 0x33, // Backspace → Delete
        0x2B => 0x30, // Tab
        0x2C => 0x31, // Space
        0x2D => 0x1B, // -
        0x2E => 0x18, // =
        0x2F => 0x21, // [
        0x30 => 0x1E, // ]
        0x31 => 0x2A, // \
        0x33 => 0x29, // ;
        0x34 => 0x27, // '
        0x35 => 0x32, // `
        0x36 => 0x2B, // ,
        0x37 => 0x2F, // .
        0x38 => 0x2C, // /
        0x39 => 0x39, // CapsLock
        // 功能键
        0x3A => 0x7A, // F1
        0x3B => 0x78, // F2
        0x3C => 0x63, // F3
        0x3D => 0x76, // F4
        0x3E => 0x60, // F5
        0x3F => 0x61, // F6
        0x40 => 0x62, // F7
        0x41 => 0x64, // F8
        0x42 => 0x65, // F9
        0x43 => 0x6C, // F10
        0x44 => 0x67, // F11
        0x45 => 0x6F, // F12
        // macOS 没有 PrintScreen/ScrollLock/Pause,映射到不常用的 F13-F15
        0x46 => 0x69, // PrintScreen → F13
        0x47 => 0x6B, // ScrollLock → F14
        0x48 => 0x71, // Pause → F15
        // 导航区
        0x49 => 0x72, // Insert → Help
        0x4A => 0x73, // Home
        0x4B => 0x74, // PageUp
        0x4C => 0x75, // Delete → ForwardDelete
        0x4D => 0x77, // End
        0x4E => 0x79, // PageDown
        0x4F => 0x7C, // Right
        0x50 => 0x7B, // Left
        0x51 => 0x7D, // Down
        0x52 => 0x7E, // Up
        // 小键盘
        0x53 => 0x47, // NumLock → KeypadClear
        0x54 => 0x4B, // KP /
        0x55 => 0x43, // KP *
        0x56 => 0x4E, // KP -
        0x57 => 0x45, // KP +
        0x58 => 0x4C, // KP Enter
        0x59 => 0x53, // KP 1
        0x5A => 0x54, // KP 2
        0x5B => 0x55, // KP 3
        0x5C => 0x56, // KP 4
        0x5D => 0x57, // KP 5
        0x5E => 0x58, // KP 6
        0x5F => 0x59, // KP 7
        0x60 => 0x5B, // KP 8
        0x61 => 0x5C, // KP 9
        0x62 => 0x52, // KP 0
        0x63 => 0x41, // KP .
        0x67 => 0x51, // KP =
        // 修饰键:Linux Super → macOS Command,Alt → Option,Ctrl → Control
        0xE0 => 0x3B, // LeftControl
        0xE1 => 0x38, // LeftShift
        0xE2 => 0x3A, // LeftAlt → Option
        0xE3 => 0x37, // LeftGUI → Command
        0xE4 => 0x3E, // RightControl
        0xE5 => 0x3C, // RightShift
        0xE6 => 0x3D, // RightAlt → RightOption
        0xE7 => 0x36, // RightGUI → RightCommand
        _ => return None,
    })
}
